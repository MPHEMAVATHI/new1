def render_sidebar():
    st.sidebar.title("AI Lung CT Analysis")
    st.sidebar.caption("Research Prototype for NSCLC CT Analysis")

    st.sidebar.markdown("### Upload CT")
    upload_mode = st.sidebar.radio(
        "Input type", ["NIfTI file (.nii / .nii.gz)", "DICOM series (ZIP)"]
    )

    uploaded_file = None
    if upload_mode.startswith("NIfTI"):
        uploaded_file = st.sidebar.file_uploader("Upload NIfTI file", type=["nii", "gz"])
    else:
        uploaded_file = st.sidebar.file_uploader("Upload DICOM ZIP", type=["zip"])

