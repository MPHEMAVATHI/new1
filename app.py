def render_evaluation_tab():
    st.header("Evaluation")
    cfg = load_config()
    report_dir = resolve_path(cfg.get("paths", {}).get("reports_dir", "reports"))
    metrics_path = report_dir / "metrics.json"

    if not metrics_path.exists():
        st.warning(
            "Model evaluation unavailable because a trained project-specific "
            "classifier has not yet been provided."
        )
        st.caption(
            "Run the training pipeline (training/train_classifier.py, then "
            "training/evaluate_model.py) to populate this tab."
        )
        return

    import json

    with metrics_path.open("r", encoding="utf-8") as f:
        metrics = json.load(f)

    if metrics.get("status") != "ok":
        st.warning(metrics.get("message", "Evaluation unavailable."))
        return

    cols = st.columns(4)
    cols[0].metric("Accuracy", f"{metrics['accuracy']:.1%}")
    cols[1].metric("Sensitivity", f"{metrics['sensitivity']:.1%}")
    cols[2].metric("Specificity", f"{metrics['specificity']:.1%}")
    auc = metrics.get("roc_auc")
    cols[3].metric("ROC-AUC", f"{auc:.3f}" if auc is not None else "N/A")

    for fname, caption in [
        ("confusion_matrix.png", "Confusion Matrix"),
        ("roc_curve.png", "ROC Curve"),
        ("pr_curve.png", "Precision-Recall Curve"),
    ]:
        fpath = report_dir / fname
        if fpath.exists():
            st.image(str(fpath), caption=caption, width=400)

    st.caption(
        "Evaluated on a held-out, patient-level test split. Performance on "
        "external patients may differ from performance on research datasets."
    )


