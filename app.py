    score_threshold = st.sidebar.slider("Detection score threshold", 0.1, 0.9, 0.5, 0.05)

    st.sidebar.markdown("### Model Information")
    status = check_model_files()
    st.sidebar.write(f"Device: **{status.device.upper()}**")
    if status.gpu_name:
        st.sidebar.write(f"GPU: {status.gpu_name}")
    st.sidebar.write(
        "Detection weights: "
        + ("✅ Loaded" if status.detection_weights_found else "⚠️ Not found (demo network)")
    )
    st.sidebar.write(
        "NSCLC classifier: "
        + ("✅ Available" if status.classifier_available else "⚠️ Not Available (demo mode)")
    )

    st.sidebar.markdown("### About Dataset")
    st.sidebar.caption(
        "Trained/developed using TCIA NSCLC Radiogenomics (211 subjects) and "
        "NSCLC Radiomics (422 subjects) — both cancer cohorts, not "
        "healthy-vs-cancer datasets. See the Dataset tab for details."
    )

    st.sidebar.markdown("### Disclaimer")
    st.sidebar.warning(DISCLAIMER)

